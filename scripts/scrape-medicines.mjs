/**
 * One-time scraping script — generates src/data/medicines.ts
 * Run: node scripts/scrape-medicines.mjs
 * Requires Node 18+ (native fetch)
 */

import { writeFileSync } from "fs";
import { fileURLToPath } from "url";
import path from "path";

const BASE = "http://www.homeoint.org/books/boericmm";
const LETTERS = "abcdefghijklmnopqrstuvwxyz".split("");
const OUT = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "../src/data/medicines.ts"
);

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

function decodeName(raw) {
  return raw
    .trim()
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&nbsp;/g, " ")
    .replace(/&#39;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/\s+/g, " ")
    .trim();
}

async function fetchLetter(letter) {
  const url = `${BASE}/${letter}.htm`;
  let html;
  try {
    const res = await fetch(url, {
      headers: {
        "User-Agent":
          "Mozilla/5.0 (compatible; NeoHomeo-Scraper/1.0; +https://neohomeo.com)",
      },
    });
    if (!res.ok) {
      console.warn(`  [skip] ${letter}.htm → HTTP ${res.status}`);
      return [];
    }
    html = await res.text();
  } catch (e) {
    console.warn(`  [skip] ${letter}.htm → ${e.message}`);
    return [];
  }

  const entries = [];
  const seen = new Set();

  // Match links like href="a/abies-c.htm" or href="./a/abies-c.htm"
  const re =
    /<a\s+href="\.?\/?([a-z]\/[a-z0-9-]+\.htm)"[^>]*>([^<]+)<\/a>/gi;
  let m;
  while ((m = re.exec(html)) !== null) {
    const htmPath = m[1].replace(/^\.\//, "");
    const name = decodeName(m[2]);
    if (!name || seen.has(htmPath)) continue;
    seen.add(htmPath);

    const abbr = htmPath.split("/")[1].replace(".htm", "");
    entries.push({
      letter: letter.toUpperCase(),
      name,
      abbr,
      path: htmPath,
    });
  }

  return entries;
}

(async () => {
  console.log("Scraping Boericke Materia Medica index…");
  const all = [];

  for (const letter of LETTERS) {
    process.stdout.write(`  ${letter.toUpperCase()} `);
    const items = await fetchLetter(letter);
    all.push(...items);
    console.log(`→ ${items.length} medicines`);
    await sleep(250);
  }

  console.log(`\nTotal: ${all.length} medicines`);

  const rows = all
    .map(
      (m) =>
        `  { letter: "${m.letter}", name: ${JSON.stringify(m.name)}, abbr: ${JSON.stringify(m.abbr)}, path: ${JSON.stringify(m.path)} },`
    )
    .join("\n");

  const output = `import type { Medicine } from "../types/student";

// Auto-generated by scripts/scrape-medicines.mjs — do not edit manually.
// Source: http://www.homeoint.org/books/boericmm/index.htm
export const MEDICINES: Medicine[] = [
${rows}
];
`;

  writeFileSync(OUT, output, "utf-8");
  console.log(`Written → ${OUT}`);
})();
